from langchain_core.prompts import ChatPromptTemplate

decision_prompt = ChatPromptTemplate.from_template(
"""
아래 마크다운 문서가 agentic chunk 생성 대상로 유효한지 판단하라.

[목표]
- 이 문서가 factual하고 self-contained한 chunk들로 분해 가능한지 먼저 판별한다.
- chunking 전에 hallucination 가능성이 높은 문서를 걸러낸다.

[판단 기준]

- useful=true 인 경우:
  ✔ 명확한 대상이 존재함 (사람, 기관, 작물, 병해, 시설, 품목 등)
  ✔ 구체적 사실이 존재함 (상태, 변화, 수치, 특성, 발생 양상, 조치사항 등)
  ✔ 문서 본문에 의미 있는 서술이 있음
  ✔ 일부 노이즈가 있어도 전체적으로 chunking 가치가 있음

- useful=false 인 경우:
  ✖ 대부분 제목, 머리말, 이미지, 캡션, 목차, 라벨로 구성됨
  ✖ factual statement로 만들 수 있는 본문이 거의 없음
  ✖ 문맥 없는 짧은 단편이 대부분임
  ✖ 내용을 추론하지 않으면 chunk 생성이 어려움

[중요 규칙]
1. JSON만 출력하라.
2. 코드블록 금지.
3. 추론해서 내용을 보완하지 말 것.
4. 문서에 실제로 있는 정보만 기준으로 판단할 것.

출력 스키마:
{{
  "is_useful": true,
  "reason": "판단 이유"
}}

문서:
{raw_text}
"""
)

meta_prompt = ChatPromptTemplate.from_template(
"""
아래 문서를 읽고, 이 문서의 모든 정보 조각(청크)에 반드시 포함되어야 할 핵심 식별 맥락을 추출하라.

[목표]
- 어떤 청크를 단독으로 읽어도 "누가, 언제, 무엇에 대한" 정보인지 알 수 있도록
- 문서 유형에 관계없이 범용적으로 동작해야 함

[규칙]
- 문서 유형을 먼저 파악하라 (컨설팅 보고서 / 연구 논문 / 계약서 / 회의록 등)
- 해당 문서에서 모든 청크에 공통으로 붙어야 할 식별자만 추출하라
- 고정 스키마 없이, 문서에서 실제로 존재하는 핵심 식별 정보만 자연어로 출력하라
- JSON만 출력. 코드블록 금지.

출력 스키마:
{{
  "doc_type": "문서 유형",
  "context_prefix": "모든 청크 앞에 붙을 자연어 맥락 문자열"
}}

[예시 출력]
컨설팅 보고서인 경우:
{{"doc_type": "현장컨설팅 결과보고서", "context_prefix": "한정식 농가의 2차 현장컨설팅(2022.12.12, 컨설턴트: 서범석) 결과에 따르면"}}

계약서인 경우:
{{"doc_type": "용역계약서", "context_prefix": "A사와 B사 간 2024.03.01 체결된 소프트웨어 용역계약서에 따르면"}}

회의록인 경우:
{{"doc_type": "회의록", "context_prefix": "2023.11.15 마케팅팀 주간회의(참석: 김철수, 이영희)에서"}}

문서:
{raw_text}
"""
)

agentic_prompt = ChatPromptTemplate.from_template(
"""
아래 입력 텍스트를 읽고 의미 단위로 청크를 생성하라.

[목표]
- 입력 텍스트를 여러 개의 self-contained chunk로 변환한다.
- 각 chunk는 단독으로 읽어도 의미가 완전히 이해되어야 한다.

[해야 할 작업]
1. 전체 내용을 요약한 md_summary를 생성한다.
2. 의미 단위로 나눈 text(chunk)를 생성한다.
3. 각 text를 기반으로 agentic_chunk를 생성한다.

--------------------------------------------------
[중요 규칙 - 반드시 지켜야 함]

1. JSON만 출력하라. 다른 텍스트 절대 출력 금지.
2. 코드블록(```) 절대 사용 금지.
3. 반드시 아래 스키마 그대로 출력할 것.
4. key 이름 절대 변경 금지.

--------------------------------------------------

[md_summary 규칙]
- 전체 텍스트의 핵심 내용만 간결하게 요약
- 과도한 설명 금지
- 추론 금지

--------------------------------------------------

[text (raw chunk) 규칙]
- 원문 기반으로 의미 단위 분리
- 하나의 chunk는 하나의 주제만 포함
- 불필요한 요약 금지

--------------------------------------------------

[agentic_chunk 규칙 - 가장 중요]

- 모든 agentic_chunk는 반드시 아래 맥락 prefix로 시작해야 한다:
  "{context_prefix}"
- prefix 뒤에 쉼표(,)를 붙이고 바로 사실 정보를 이어서 작성할 것
- "이 보고서는", "본 문서는", "이 문장은", "해당 내용은" 절대 사용 금지
- 문서 자체를 설명하는 표현 금지

- 반드시 factual statement로 작성:
  ✔ 대상 (사람 / 기관 / 작물 / 시설 등)
  ✔ 수치 (금액, 면적, 온도, 기간 등)
  ✔ 상태 (정상, 부족, 결정 등)
  ✔ 조치사항 (필요, 권장, 결정 등)

- raw chunk의 정보를 절대 누락하지 말 것
- 불필요한 해석, 추론, 일반화 금지
- 표 형태 → 자연스러운 문장으로 변환

--------------------------------------------------

[좋은 예] (context_prefix는 문서마다 다르며, 아래는 예시일 뿐임)

# 컨설팅 보고서
"한정식 농가의 2차 현장컨설팅(2022.12.12) 결과에 따르면, 딸기(금실) 재배 면적은 2,400m²이며 양액재배 방식이 적용된다."

# 농업 병해 기술자료
"고추(Capsicum annuum)에서 발생하는 갈색점무늬병(Cercospora leaf spot)에 따르면, 병은 잎, 잎자루, 가지, 과경에 발생하며 초기에는 흰색 점무늬가 형성되고 이후 갈색 원형 병반으로 확대된다."

# 연구 논문
"김철수 외(2023)의 토양 미생물 연구에 따르면, 유기물 첨가 처리구에서 미생물 활성이 대조군 대비 37% 증가하였다."

--------------------------------------------------

[나쁜 예]

"딸기 재배 면적은 2,400m²이며 양액재배 방식이 적용된다."  ← prefix 없음
"계약 기간은 6개월이다."  ← prefix 없음
"이 보고서에 따르면 ..."  ← 금지 표현
"이 문서는 농업 정보를 설명한다."  ← 문서 설명

--------------------------------------------------

입력 제목: {header}

입력 내용:
{raw_text}

맥락 prefix: {context_prefix}

--------------------------------------------------

출력 스키마 (반드시 그대로):

{{
  "md_summary": "...",
  "chunks": [
    {{
      "text": "...",
      "agentic_chunk": "..."
    }}
  ]
}}
"""
)