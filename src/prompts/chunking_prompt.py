agentic_prompt = ChatPromptTemplate.from_template(
"""
아래 입력 텍스트를 읽고 QA 생성에 활용할 수 있는 유의미한 정보 단위를 추출하라.

입력 텍스트:
{raw_text}

문서 요약:
{md_summary}

[목표]
- QA 쌍을 만들 수 있는 factual하고 구체적인 정보 단위만 추출한다.
- 질문을 뽑기 어려운 단편적이거나 맥락 없는 내용은 추출하지 않는다.

[출력 스키마]
{{
  "chunks": [
    {{
      "raw_chunk": "...",
      "agentic_chunk": "..."
    }}
  ]
}}

[해야 할 작업]
1. QA 생성에 적합한 정보 단위를 raw_chunk로 추출한다.
  [raw_chunk 추출 기준]
  - 구체적 수치, 조건, 방법, 원인, 결과가 포함된 내용
  - 단독으로 읽어도 의미가 완전한 factual statement
  - 질문을 자연스럽게 만들 수 있는 내용
  - 아래는 추출하지 않는다:
    ✖ 단순 나열이나 목록 제목만 있는 내용
    ✖ 맥락 없이 단편적인 내용
    ✖ 이미 다른 chunk에서 다룬 내용의 반복

2. raw_chunk에 md_summary의 맥락을 결합하여 agentic_chunk를 생성한다.
    [agentic_chunk 생성 규칙 - 가장 중요]
    - raw_chunk의 정보를 절대 누락하지 말 것
    - md_summary에 날짜, 농가명, 수행기관, 문서명 등 식별 가능한 정보가 있으면 반드시 agentic_chunk 앞부분에 포함할 것
    - 단순히 "컨설팅에 따르면" 같은 포괄적 표현 금지 — 반드시 구체적 주체(농가명, 기관명)와 시점(날짜, 기간)을 명시할 것
    - 단일 문장으로 완전한 의미를 전달할 것
    - "이 보고서는", "본 문서는" 등 문서 자체를 대명사로 지칭하는 표현 금지

    [예시 1]
    md_summary: "2022년 11월 10일, 김은상 대표의 딸기 스마트팜 컨설팅이 진행되었으며, 온도·습도 관리 문제와 병해 예방 관리 부족이 지적되었다."
    raw_chunk: "배지의 EC는 1.6, pH는 6으로, 급액 농도는 작물 생육상에 맞춰 조정해야 한다는 권고가 있었다."

    ✔ 좋은 agentic_chunk의 예: "김은상 대표 딸기 스마트팜 컨설팅(2022.11.10) 결과, 배지의 EC 1.6, pH 6을 기준으로 급액 농도를 작물 생육상에 맞춰 조정할 것을 권고하였다."
    ✖ 나쁜 agentic_chunk의 예: "배지 관리에서 배지의 EC는 1.6, pH는 6으로, 급액 농도는 작물 생육상에 맞춰 조정해야 한다는 권고가 있었다." ← md_summary의 컨설팅 날짜(2022.11.10)와 농가 대표(김은상) 정보를 반영하지 않음

    [예시 2]
    md_summary: "한국온실작물연구소가 수행한 딸기 스마트팜 농가 생육관리 컨설팅(2022.10.25~12.24)으로, 40개 농가의 작물 재배 관리와 환경 제어 시스템 개선 의견이 제시되었다."
    raw_chunk: "첫 번째 농가는 면적 6,500㎡에서 양액 재배와 단동 비닐 형태를 가지고 있으며, 고용인력은 총 3명이다."

    ✔ 좋은 agentic_chunk의 예: "한국온실작물연구소가 수행한 딸기 스마트팜 농가 생육관리 컨설팅(2022.10.25~12.24) 결과, 첫 번째 농가는 면적 6,500㎡에서 양액 재배 및 단동 비닐 형태로 운영하며 고용인력은 총 3명이다."
    ✖ 나쁜 agentic_chunk의 예: "첫 번째 농가는 면적 6,500㎡로 양액 재배와 단동 비닐 형태를 가지고 있으며, 고용인력은 총 3명이다." ← md_summary의 컨설팅 시점과 수행기관 정보를 반영하지 않음

    [예시 3]
    md_summary: "딸기 스마트팜 재배 가이드로, 정식 이후 초세 관리와 생육속도 판단 기준을 설명한다."
    raw_chunk: "활착이 완료되면 크라운 경경은 1주에 약 5~8mm씩 증가하여 초세가 호전되고 있음을 확인할 수 있다."

    ✔ 좋은 agentic_chunk의 예: "딸기 스마트팜 재배 가이드에 따르면, 정식 후 활착 완료(약 2주 경과) 시점부터 크라운 경경이 1주에 5~8mm씩 증가하여 초세 호전 여부를 확인할 수 있다."
    ✖ 나쁜 agentic_chunk의 예: "크라운 경경은 1주에 5~8mm씩 증가한다." ← 어떤 작물의, 어떤 조건에서의 정보인지 맥락이 없음
"""
)

